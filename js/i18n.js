function setLanguage(lang) {
  if (!['en', 'fr', 'ar'].includes(lang)) lang = 'en';
  localStorage.setItem('lang', lang);
  
  document.documentElement.lang = lang;
  if (lang === 'ar') {
    document.documentElement.setAttribute('dir', 'rtl');
    document.documentElement.classList.add('ar');
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
    document.documentElement.classList.remove('ar');
  }

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === 'INPUT' && el.getAttribute('placeholder') !== null) {
        el.setAttribute('placeholder', translations[lang][key]);
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Update active state in switcher
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('text-primary', 'font-bold');
      btn.classList.remove('text-[var(--text-secondary)]');
    } else {
      btn.classList.remove('text-primary', 'font-bold');
      btn.classList.add('text-[var(--text-secondary)]');
    }
  });

  // Refresh currency display if main.js is loaded
  if (window.setCurrency) {
    const currentCurr = localStorage.getItem('currency') || 'USD';
    window.setCurrency(currentCurr);
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const currentLang = localStorage.getItem('lang') || 'en';
  setLanguage(currentLang);
  
  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn) {
      e.preventDefault();
      const l = btn.dataset.lang;
      if (l) setLanguage(l);
    }
  });
});
